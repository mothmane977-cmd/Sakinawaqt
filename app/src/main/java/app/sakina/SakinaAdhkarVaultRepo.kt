    private fun todayKey(): String = SimpleDateFormat("yyyy-MM-dd", Locale.US).format(Date())

    fun getBaqiyatTotal(ctx: Context): Long =
        ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE).getLong("baqiyat_total", 0L)

    fun getBaqiyatToday(ctx: Context): Int {
        val sp = ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val savedDay = sp.getString("baqiyat_day", "")
        return if (savedDay == todayKey()) sp.getInt("baqiyat_today", 0) else 0
    }

    fun incrementBaqiyat(ctx: Context, delta: Int = 1): Pair<Long, Int> {
        val sp = ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val key = todayKey()
        val newTotal = sp.getLong("baqiyat_total", 0L) + delta
        val curToday = if (sp.getString("baqiyat_day", "") == key) sp.getInt("baqiyat_today", 0) else 0
        val newToday = curToday + delta
        sp.edit()
            .putLong("baqiyat_total", newTotal)
            .putString("baqiyat_day", key)
            .putInt("baqiyat_today", newToday)
            .apply()
        markTodayStreakActive(ctx)
        return newTotal to newToday
    }

    fun markTodayStreakActive(ctx: Context) {
        val sp = ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val set = sp.getStringSet("streak_days", emptySet())?.toMutableSet() ?: mutableSetOf()
        set.add(todayKey())
        sp.edit().putStringSet("streak_days", set).apply()
    }

    fun getLast14DaysStreak(ctx: Context): List<Pair<String, Boolean>> {
        val sp = ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val done = sp.getStringSet("streak_days", emptySet()) ?: emptySet()
        val fmtKey = SimpleDateFormat("yyyy-MM-dd", Locale.US)
        val fmtDay = SimpleDateFormat("dd", Locale.US)
        val res = mutableListOf<Pair<String, Boolean>>()
        val cal = Calendar.getInstance()
        cal.add(Calendar.DAY_OF_YEAR, -13)
        for (i in 0 until 14) {
            val k = fmtKey.format(cal.time)
            res.add(fmtDay.format(cal.time) to done.contains(k))
            cal.add(Calendar.DAY_OF_YEAR, 1)
        }
        return res
    }

    fun getCurrentStreakCount(ctx: Context): Int {
        val sp = ctx.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val done = sp.getStringSet("streak_days", emptySet()) ?: emptySet()
        val fmtKey = SimpleDateFormat("yyyy-MM-dd", Locale.US)
        val cal = Calendar.getInstance()
        var streak = 0
        for (i in 0 until 365) {
            if (done.contains(fmtKey.format(cal.time))) {
                streak++
                cal.add(Calendar.DAY_OF_YEAR, -1)
            } else {
                break
            }
        }
        return streak
    }

