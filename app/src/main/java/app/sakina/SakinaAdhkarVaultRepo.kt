    fun normalizeArabic(raw: String): String {
        val noDiacritics = raw.replace(Regex("[\u064B-\u065F\u0670\u0640]"), "")
        return noDiacritics
            .replace('أ', 'ا')
            .replace('إ', 'ا')
            .replace('آ', 'ا')
            .replace('ة', 'ه')
            .replace('ى', 'ي')
            .trim()
            .lowercase(Locale.ROOT)
    }

    fun detectCurrentSlot(ctx: Context): DailyWirdSlot {
        val now = Calendar.getInstance()
        val hour = now.get(Calendar.HOUR_OF_DAY)
        try {
            val events = PrayerEngine.events(ctx, 0)
            val nowMs = now.timeInMillis
            val prayerIndices = listOf(0, 2, 3, 4, 5) // Fajr, Dhuhr, Asr, Maghrib, Isha
            for (pIdx in prayerIndices) {
                val evTime = events.firstOrNull { it.first == pIdx }?.second?.time ?: continue
                val diffMin = (nowMs - evTime) / 60_000L
                if (diffMin in 0L..12L) return DailyWirdSlot.ADHAN
                if (diffMin in 13L..35L) return DailyWirdSlot.POST_PRAYER
            }
        } catch (_: Exception) {
        }
        return when (hour) {
            in 4..11 -> DailyWirdSlot.MORNING
            in 15..20 -> DailyWirdSlot.EVENING
            in 21..23, in 0..3 -> DailyWirdSlot.SLEEP
            else -> DailyWirdSlot.POST_PRAYER
        }
    }

