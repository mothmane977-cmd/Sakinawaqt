            DailyWirdSlot.POST_PRAYER -> postPrayerItems
            DailyWirdSlot.ADHAN -> adhanItems
            DailyWirdSlot.SLEEP -> sleepItems
        }
        return when (level) {
            VaultWirdLevel.COMPLETE -> all
            VaultWirdLevel.CURATED -> all.filter { it.minLevel == VaultWirdLevel.COMPACT || it.minLevel == VaultWirdLevel.CURATED }
            VaultWirdLevel.COMPACT -> all.filter { it.minLevel == VaultWirdLevel.COMPACT }
        }
    }

