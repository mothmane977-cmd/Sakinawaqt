    fun normalizeAr(s: String): String {
        val noDiacritics = s.replace(Regex("[\u064B-\u065F\u0670\u0640]"), "")
        return noDiacritics
            .replace('أ', 'ا')
            .replace('إ', 'ا')
            .replace('آ', 'ا')
            .replace('ة', 'ه')
            .replace('ى', 'ي')
            .trim()
            .lowercase()
    }

    fun isWeeklyDayDone(ctx: Context, dayIdx: Int): Boolean =
        sp(ctx).getBoolean("week_sunnah_d_$dayIdx", false)

    fun toggleWeeklyDay(ctx: Context, dayIdx: Int) {
        val cur = isWeeklyDayDone(ctx, dayIdx)
        sp(ctx).edit().putBoolean("week_sunnah_d_$dayIdx", !cur).apply()
    }

    fun isDailySunnahDone(ctx: Context, id: String): Boolean =
        sp(ctx).getBoolean("daily_s_$id", false)

    fun toggleDailySunnah(ctx: Context, id: String) {
        val cur = isDailySunnahDone(ctx, id)
        sp(ctx).edit().putBoolean("daily_s_$id", !cur).apply()
    }

