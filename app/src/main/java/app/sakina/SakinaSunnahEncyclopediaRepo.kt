enum class SunnahSubSection(val labelAr: String) {
    DAILY("هَديُه ﷺ"),
    BOOKS("المتون"),
    SHAMAIL("الشمائل"),
    WEAK_SHIELD("لا يصح")
}

enum class HadithGrade(val labelAr: String, val colorHex: Long) {
    SAHIH("صحيح", 0xFF1EE3A8),
    HASAN("حسن", 0xFF60A5FA),
    DAIF("ضعيف / لا يصح", 0xFFF87171)
}

