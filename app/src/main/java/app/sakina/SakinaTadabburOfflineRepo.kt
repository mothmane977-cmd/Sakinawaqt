    private const val PREF_NAME = "nurqunoot_tadabbur_v66"
    private fun sp(ctx: Context) = ctx.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)

    fun favoriteFawaidIds(ctx: Context): Set<String> {
        val raw = sp(ctx).getString("fav_fawaid", "") ?: ""
        return if (raw.isBlank()) emptySet() else raw.split(",").filter { it.isNotBlank() }.toSet()
    }

    fun toggleFavoriteFawaid(ctx: Context, id: String): Set<String> {
        val cur = favoriteFawaidIds(ctx).toMutableSet()
        if (!cur.add(id)) cur.remove(id)
        sp(ctx).edit().putString("fav_fawaid", cur.joinToString(",")).apply()
        return cur
    }

